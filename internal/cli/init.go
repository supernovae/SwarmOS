package cli

import (
	"fmt"
	"io"
	"maps"
	"regexp"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/supernovae/swarmos/internal/harness"
	"github.com/supernovae/swarmos/internal/tracker"
)

func newInitCmd(rootOpts *RootOptions) *cobra.Command {
	var force bool
	var syncLabels bool
	var swarmVersion string
	var templateDir string
	var verbose bool
	var asJSON bool
	var forkCoordinator bool
	var dryRun bool

	cmd := &cobra.Command{
		Use:   "init",
		Short: "Initialize .swarm/ harness, GitHub templates, and multi-agent slash commands",
		Long: `Initialize or upgrade the SwarmOS harness. Rerun it after installing a new swarm:
files that are still exactly as SwarmOS generated them are updated, and files you
edited or created yourself are kept and listed (--force replaces files at SwarmOS
paths). Your other workflows are never edited, and an existing AGENTS.md gets a
marked SwarmOS section instead of being replaced. Generated workflows
install this build of swarm (or keep the repository's existing pin when run
from a development build). --fork-coordinator adds the fork coordinator
workflow; once present, later runs keep it current. --dry-run reports what would
change, with diffs for existing files, and writes nothing.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) (runErr error) {
			defer func() { reportJSONFailure(cmd, asJSON, "repo-init", runErr) }()
			if dryRun && syncLabels {
				return fmt.Errorf("--dry-run only previews files; rerun without it to --sync-labels")
			}
			repoRoot := rootOpts.resolveRepoRoot()
			pin, pinNote := resolveSwarmPin(swarmVersion, Version, Commit, repoRoot)
			res, err := harness.InitRepository(harness.InitOptions{
				RepoRoot:        repoRoot,
				Force:           force,
				SwarmVersion:    pin,
				TemplateDir:     templateDir,
				ForkCoordinator: forkCoordinator,
				DryRun:          dryRun,
			})
			if err != nil {
				return err
			}

			syncedLabels := 0
			out := cmd.OutOrStdout()
			if asJSON {
				out = io.Discard
			}
			if dryRun {
				fmt.Fprintf(out, "Previewed %s harness (nothing written): %d to create, %d to update, %d already current\n", res.Stack.Language, len(res.CreatedFiles), len(res.UpdatedFiles), len(res.CurrentFiles))
			} else {
				fmt.Fprintf(out, "Initialized %s harness: %d created, %d updated, %d already current\n", res.Stack.Language, len(res.CreatedFiles), len(res.UpdatedFiles), len(res.CurrentFiles))
			}
			would := func(done, planned string) string {
				if dryRun {
					return planned
				}
				return done
			}
			if verbose {
				for _, file := range res.CreatedFiles {
					fmt.Fprintf(out, "  %s %s\n", would("created", "would create"), file)
				}
				for _, file := range res.UpdatedFiles {
					fmt.Fprintf(out, "  %s %s\n", would("updated", "would update"), file)
				}
			}
			for _, file := range res.SectionFiles {
				fmt.Fprintf(out, "  %s the SwarmOS section to your %s (only the marked section is managed)\n", would("added", "would add"), file)
			}
			for _, file := range res.CustomizedFiles {
				fmt.Fprintf(out, "  %s your edits to %s (review it against this version, or rerun with --force to replace it)\n", would("kept", "would keep"), file)
			}
			for _, file := range res.PreservedFiles {
				fmt.Fprintf(out, "  %s existing %s as is (not generated by SwarmOS)\n", would("left", "would leave"), file)
			}
			for _, file := range res.RemovedFiles {
				fmt.Fprintf(out, "  %s %s (no longer generated by SwarmOS, and unmodified)\n", would("removed", "would remove"), file)
			}
			if dryRun && verbose {
				for _, file := range slices.Sorted(maps.Keys(res.Diffs)) {
					fmt.Fprintf(out, "\n%s", res.Diffs[file])
				}
			} else if dryRun && len(res.Diffs) > 0 {
				fmt.Fprintf(out, "Rerun with --verbose or --json to see diffs for the %d existing files.\n", len(res.Diffs))
			}
			if pinNote != "" && (len(res.CreatedFiles) > 0 || len(res.UpdatedFiles) > 0) {
				res.Warnings = append(res.Warnings, pinNote)
			}
			for _, warning := range res.Warnings {
				fmt.Fprintln(cmd.ErrOrStderr(), warning)
			}

			if syncLabels {
				tr, err := rootOpts.resolveTracker(cmd)
				if err != nil {
					return err
				}
				labels := tracker.DefaultSwarmLabels()
				if err := tr.EnsureLabels(cmd.Context(), labels); err != nil {
					return fmt.Errorf("failed to sync labels on %s: %w", tr.BackendName(), err)
				}
				fmt.Fprintf(out, "Synced %d swarm:* labels on %s\n", len(labels), tr.BackendName())
				syncedLabels = len(labels)
			}
			if asJSON {
				report := map[string]any{"kind": "repo-init", "status": "initialized", "language": res.Stack.Language, "created": res.CreatedFiles, "updated": res.UpdatedFiles, "current": res.CurrentFiles, "customized": res.CustomizedFiles, "preserved": res.PreservedFiles, "sections": res.SectionFiles, "removed": res.RemovedFiles, "warnings": res.Warnings, "synced_labels": syncedLabels}
				if dryRun {
					report["status"] = "dry-run"
					report["diffs"] = res.Diffs
				}
				return writeJSON(cmd, report)
			}
			return nil
		},
	}

	cmd.Flags().BoolVar(&force, "force", false, "Overwrite existing .swarm/ and template files")
	cmd.Flags().BoolVar(&syncLabels, "sync-labels", false, "Idempotently create swarm:* labels on the issue tracker")
	cmd.Flags().StringVar(&swarmVersion, "swarm-version", "", "Override the SwarmOS release (v0.6.0 or newer) or full commit SHA that generated workflows install (defaults to this build)")
	cmd.Flags().BoolVar(&forkCoordinator, "fork-coordinator", false, "Generate .github/workflows/swarm-fork-coordinator.yml for --fork contributor mode")
	cmd.Flags().StringVar(&templateDir, "template-dir", "", "Directory of custom GitHub Issue Forms (.yml/.yaml) and .swarm/{rules,skills}/*.md templates")
	cmd.Flags().BoolVar(&dryRun, "dry-run", false, "Report what init would change, with diffs for existing files, without writing anything")
	cmd.Flags().BoolVar(&verbose, "verbose", false, "List individual created and preserved files")
	cmd.Flags().BoolVar(&asJSON, "json", false, "Emit created and preserved files as JSON")
	return cmd
}

// resolveSwarmPin chooses the SwarmOS version generated workflows install: an
// explicit override, this release, the exact commit of a clean build, or the
// pin the repository's workflows already use.
func resolveSwarmPin(override, version, commit, repoRoot string) (pin, note string) {
	if override != "" {
		return override, ""
	}
	if !strings.HasSuffix(version, "+dirty") {
		named := strings.Contains(version, "dev") || strings.Contains(version, "snapshot")
		if release := "v" + strings.TrimPrefix(version, "v"); !named && harness.ValidateSwarmVersionPin(release) == nil {
			if pseudoVersion.MatchString(release) {
				return release, fmt.Sprintf("generated workflows install swarm %s, built from an unreleased commit; push that commit before CI runs", release)
			}
			return release, ""
		}
		if fullCommit.MatchString(commit) {
			return commit, fmt.Sprintf("generated workflows install swarm at commit %s from this development build; push that commit before CI runs", commit)
		}
	}
	return harness.ExistingSwarmPin(repoRoot), ""
}

var fullCommit = regexp.MustCompile(`^[0-9a-f]{40}$`)

// pseudoVersion matches Go's version for an untagged commit (vX.Y.Z-0.TIMESTAMP-COMMIT).
var pseudoVersion = regexp.MustCompile(`-(?:0\.)?\d{14}-[0-9a-f]{12}$`)

// pinFor resolves the default workflow pin for repoRoot without an override.
func pinFor(repoRoot string) string {
	pin, _ := resolveSwarmPin("", Version, Commit, repoRoot)
	return pin
}
