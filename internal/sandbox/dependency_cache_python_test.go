func TestPythonUVExportRunsNoBuildBackend(t *testing.T) {
	if _, err := exec.LookPath("uv"); err != nil {
		t.Skip("uv is not on PATH")
	}
	sentinel := filepath.Join(resolvedTempDir(t), "backend-ran")
	backend := "open(" + strconv.Quote(sentinel) + ", 'w').write('ran')\n" +
		"def prepare_metadata_for_build_wheel(*a, **k): raise SystemExit(1)\n" +
		"def build_wheel(*a, **k): raise SystemExit(1)\n"
	pyproject := "[build-system]\nrequires = []\nbuild-backend = \"backend\"\nbackend-path = [\".\"]\n\n" +
		"[project]\nname = \"demo\"\ndynamic = [\"version\"]\nrequires-python = \">=3.8\"\ndependencies = [\"needed==1.0\"]\n"
	lock := `version = 1
revision = 3
requires-python = ">=3.8"

[[package]]
name = "demo"
source = { editable = "." }
dependencies = [
    { name = "needed" },
]

[package.metadata]
requires-dist = [{ name = "needed", specifier = "==1.0" }]

[[package]]
name = "needed"
version = "1.0"
source = { registry = "https://pypi.org/simple" }
wheels = [
    { url = "https://files.pythonhosted.org/packages/needed-1.0-py3-none-any.whl", hash = "sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb", size = 10 },
]
`
	var exported string
	previous := runPrefetchCommand
	runPrefetchCommand = func(ctx context.Context, dir string, env, argv []string) ([]byte, []byte, error) {
		if argv[0] == "uv" {
			return previous(ctx, dir, env, argv)
		}
		data, _ := os.ReadFile(argv[len(argv)-1])
		exported = string(data)
		return nil, nil, nil
	}
	t.Cleanup(func() { runPrefetchCommand = previous })
	repo, base := pythonRepo(t, map[string]string{"pyproject.toml": pyproject, "backend.py": backend, "uv.lock": lock})
	if _, err := PrepareDependencyCaches(t.Context(), AgentDependencyCache, repo, base, resolvedTempDir(t), PerRepository); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(sentinel); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("uv export ran the build backend: %v", err)
	}
	if !strings.Contains(exported, "needed==1.0") {
		t.Fatalf("exported requirements = %q", exported)
	}
}
