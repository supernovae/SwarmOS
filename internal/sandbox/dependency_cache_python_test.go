func TestPythonPrefetchCommandIsFetchOnly(t *testing.T) {
	pip := func(dest string, extra []string, file string) []string {
		argv := append(slices.Clone(pythonPipDownloadArgv), "--dest", dest)
		return append(append(argv, extra...), "-r", file)
	}
	for _, tc := range []struct {
		name  string
		files map[string]string
		// want lists each call as uv, or pip:<requirements file label>.
		want []string
	}{
		{"requirements only", map[string]string{"requirements.txt": "needed==1.0\n", "requirements-dev.txt": "-r requirements.txt\nother>=2\n"}, []string{"pip:requirements-dev.txt", "pip:requirements.txt"}},
		{"uv.lock only", map[string]string{"uv.lock": "version = 1\n", "pyproject.toml": testPyproject}, []string{"uv", "pip:export"}},
		{"both", map[string]string{"uv.lock": "version = 1\n", "pyproject.toml": testPyproject, "requirements.txt": "needed==1.0\n"}, []string{"uv", "pip:export", "pip:requirements.txt"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			calls := stubPythonPrefetch(t, testUVExport, nil)
			repo, base := pythonRepo(t, tc.files)
			deps, err := PrepareDependencyCaches(t.Context(), AgentDependencyCache, repo, base, resolvedTempDir(t), PerRepository)
			if err != nil {
				t.Fatal(err)
			}
			dest := deps.Caches[0].Dir
			if len(*calls) != len(tc.want) {
				t.Fatalf("calls = %+v, want %v", *calls, tc.want)
			}
			for i, call := range *calls {
				if insideDir(repo, call.Dir) {
					t.Errorf("%v ran inside the worktree", call.Argv)
				}
				switch want := tc.want[i]; {
				case want == "uv":
					if !slices.Equal(call.Argv[:len(pythonUVExportArgv)], pythonUVExportArgv) || call.Argv[len(call.Argv)-2] != "-o" {
						t.Errorf("uv argv = %q", call.Argv)
					}
					for _, flag := range []string{"--frozen", "--offline", "--no-build", "--no-config", "--no-emit-project"} {
						if !slices.Contains(call.Argv, flag) {
							t.Errorf("uv export runs without %s: %q", flag, call.Argv)
						}
					}
				case want == "pip:export":
					file := call.Argv[len(call.Argv)-1]
					if !slices.Equal(call.Argv, pip(dest, []string{"--no-deps", "--require-hashes"}, file)) || !strings.Contains(call.Files[filepath.Base(file)], "needed==1.0") {
						t.Errorf("pip argv = %q", call.Argv)
					}
				default:
					file := call.Argv[len(call.Argv)-1]
					if filepath.Base(file) != strings.TrimPrefix(want, "pip:") || !slices.Equal(call.Argv, pip(dest, nil, file)) {
						t.Errorf("pip argv = %q, want %s", call.Argv, want)
					}
				}
				if call.Argv[0] != "uv" && (!slices.Contains(call.Argv, "--only-binary=:all:") || !containsRun(call.Argv, []string{"--dest", dest})) {
					t.Errorf("pip download is not wheel-only into the cache: %q", call.Argv)
				}
			}
		})
	}
}

