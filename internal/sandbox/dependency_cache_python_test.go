// pythonHostHome points HostToolchains at a synthetic HOME holding host
// pip, uv and Poetry caches and a uv-managed interpreter directory.
func pythonHostHome(t *testing.T) map[string]string {
	t.Helper()
	home := resolvedTempDir(t)
	paths := map[string]string{}
	for name, rel := range map[string]string{
		"pip": ".cache/pip", "uv": ".cache/uv", "poetry": ".cache/pypoetry", "interpreters": ".local/share/uv/python",
	} {
		paths[name] = filepath.Join(home, filepath.FromSlash(rel))
		if err := os.MkdirAll(paths[name], 0o755); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("HOME", home)
	for _, key := range []string{"XDG_CACHE_HOME", "XDG_DATA_HOME", "PIP_CACHE_DIR", "UV_CACHE_DIR", "UV_PYTHON_INSTALL_DIR", "POETRY_CACHE_DIR"} {
		t.Setenv(key, "")
	}
	return paths
}

func TestPythonDependencyCacheSyntheticHome(t *testing.T) {
	for _, tc := range []struct {
		name  string
		files map[string]string
	}{
		{"requirements", map[string]string{"requirements-dev.txt": "needed==1.0\n"}},
		{"uv.lock", map[string]string{"uv.lock": "version = 1\n", "pyproject.toml": testPyproject}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			host := pythonHostHome(t)
			stubPythonPrefetch(t, testUVExport, nil)
			repo, base := pythonRepo(t, tc.files)
			userCache := resolvedTempDir(t)
			deps, err := PrepareDependencyCaches(t.Context(), AgentDependencyCache, repo, base, userCache, PerRepository)
			if err != nil {
				t.Fatal(err)
			}
			key, err := repositoryCacheKey(t.Context(), repo)
			if err != nil {
				t.Fatal(err)
			}
			dir := filepath.Join(userCache, "swarm", "agent-deps", key, "python")
			if len(deps.Caches) != 1 || deps.Caches[0] != (DependencyCache{Ecosystem: "python", EnvKey: "PIP_FIND_LINKS", Dir: dir}) {
				t.Fatalf("caches = %+v, want python at %s", deps.Caches, dir)
			}

			work := resolvedTempDir(t)
			flags, err := executorFlags(work, false, nil, deps, "true", nil)
			if err != nil {
				t.Fatal(err)
			}
			policy := codexPolicy("/usr/bin/codex", work, resolvedTempDir(t), false, nil, deps)
			env := nativeEnv(resolvedTempDir(t), false, deps)
			for name, args := range map[string][]string{"bwrap": flags, "codex": policy, "native env": env} {
				joined := strings.Join(args, "\n")
				for _, cache := range []string{"pip", "uv", "poetry"} {
					if strings.Contains(joined, host[cache]) {
						t.Errorf("%s exposes the host %s cache: %s", name, cache, joined)
					}
				}
			}
			if !containsRun(flags, []string{"--ro-bind", dir, dir}) || !containsRun(flags, []string{"--setenv", "PIP_FIND_LINKS", dir}) {
				t.Errorf("bwrap must bind the cache read-only and set PIP_FIND_LINKS: %v", flags)
			}
			if containsRun(flags, []string{"--bind", dir, dir}) {
				t.Error("per-repository cache is writable")
			}
			if !strings.Contains(strings.Join(policy, " "), strconv.Quote(dir)+`="read"`) {
				t.Errorf("codex policy does not grant the cache read-only: %v", policy)
			}
			if !slices.Contains(env, "PIP_FIND_LINKS="+dir) {
				t.Errorf("native env = %v", env)
			}
			if interpreters := host["interpreters"]; !containsRun(flags, []string{"--ro-bind", interpreters, interpreters}) {
				t.Errorf("bwrap must still mount uv-managed interpreters: %v", flags)
			}
		})
	}
}

