// writePythonIndex lays out a file:// PEP 503 index under root/simple
// holding each distribution file.
func writePythonIndex(t *testing.T, root string, dists map[string]map[string][]byte) string {
	t.Helper()
	for project, files := range dists {
		dir := filepath.Join(root, "simple", project)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
		var links strings.Builder
		for name, data := range files {
			if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
				t.Fatal(err)
			}
			links.WriteString(`<a href="` + name + `">` + name + "</a>\n")
		}
		writeWorkerFixture(t, dir, "index.html", "<!DOCTYPE html><html><body>\n"+links.String()+"</body></html>\n")
	}
	return "file://" + filepath.ToSlash(filepath.Join(root, "simple"))
}

func testWheel(t *testing.T, name, version string) []byte {
	t.Helper()
	path := filepath.Join(t.TempDir(), "w.whl")
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	zw := zip.NewWriter(f)
	info := name + "-" + version + ".dist-info/"
	for file, content := range map[string]string{
		name + "/__init__.py": "",
		info + "METADATA":     "Metadata-Version: 2.1\nName: " + name + "\nVersion: " + version + "\n",
		info + "WHEEL":        "Wheel-Version: 1.0\nGenerator: test\nRoot-Is-Purelib: true\nTag: py3-none-any\n",
		info + "RECORD":       "",
	} {
		w, err := zw.Create(file)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := w.Write([]byte(content)); err != nil {
			t.Fatal(err)
		}
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

// testSdist is an sdist whose setup.py writes sentinel when run.
func testSdist(t *testing.T, name, version, sentinel string) []byte {
	t.Helper()
	path := filepath.Join(t.TempDir(), "s.tar.gz")
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	gz := gzip.NewWriter(f)
	tw := tar.NewWriter(gz)
	root := name + "-" + version + "/"
	for file, content := range map[string]string{
		root + "PKG-INFO": "Metadata-Version: 2.1\nName: " + name + "\nVersion: " + version + "\n",
		root + "setup.py": "open(" + strconv.Quote(sentinel) + ", 'w').write('ran')\nfrom setuptools import setup\nsetup(name=" + strconv.Quote(name) + ", version=" + strconv.Quote(version) + ")\n",
	} {
		if err := tw.WriteHeader(&tar.Header{Name: file, Mode: 0o644, Size: int64(len(content))}); err != nil {
			t.Fatal(err)
		}
		if _, err := tw.Write([]byte(content)); err != nil {
			t.Fatal(err)
		}
	}
	for _, c := range []interface{ Close() error }{tw, gz, f} {
		if err := c.Close(); err != nil {
			t.Fatal(err)
		}
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func TestPythonPrefetchRunsNoPackageCode(t *testing.T) {
	requirePipDownload(t)
	sentinel := filepath.Join(resolvedTempDir(t), "setup-py-ran")
	t.Setenv("PIP_INDEX_URL", writePythonIndex(t, resolvedTempDir(t), map[string]map[string][]byte{
		"evil": {"evil-1.0.tar.gz": testSdist(t, "evil", "1.0", sentinel)},
	}))
	repo, base := pythonRepo(t, map[string]string{"requirements.txt": "evil==1.0\n"})
	userCache := resolvedTempDir(t)
	_, err := PrepareDependencyCaches(t.Context(), AgentDependencyCache, repo, base, userCache, PerRepository)
	if err == nil || !strings.Contains(err.Error(), "evil") || !strings.Contains(err.Error(), "sdist-only") {
		t.Fatalf("an sdist-only dependency must be reported: %v", err)
	}
	if _, err := os.Stat(sentinel); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("prefetch ran the sdist's setup.py: %v", err)
	}
	if matches, _ := filepath.Glob(filepath.Join(userCache, "swarm", "*", "*", "python", "evil*")); len(matches) != 0 {
		t.Fatalf("prefetch stored %v", matches)
	}
}

