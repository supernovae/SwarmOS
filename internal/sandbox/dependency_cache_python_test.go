// pythonCall is one stubbed prefetch command. Files holds the requirements
// file pip read (-r) or, for uv, the project files it ran against.
type pythonCall struct {
	Dir   string
	Env   []string
	Argv  []string
	Files map[string]string
}

// stubPythonPrefetch replaces the host prefetch runner. uv export writes
// exported to its -o file; pip download calls run, if set, which may fail.
func stubPythonPrefetch(t *testing.T, exported string, run func(argv []string) ([]byte, error)) *[]pythonCall {
	t.Helper()
	var calls []pythonCall
	previous := runPrefetchCommand
	runPrefetchCommand = func(_ context.Context, dir string, env, argv []string) ([]byte, []byte, error) {
		call := pythonCall{Dir: dir, Env: env, Argv: slices.Clone(argv), Files: map[string]string{}}
		if argv[0] == "uv" {
			entries, _ := os.ReadDir(dir)
			for _, e := range entries {
				data, _ := os.ReadFile(filepath.Join(dir, e.Name()))
				call.Files[e.Name()] = string(data)
			}
			calls = append(calls, call)
			out := argv[slices.Index(argv, "-o")+1]
			return nil, nil, os.WriteFile(out, []byte(exported), 0o600)
		}
		file := argv[slices.Index(argv, "-r")+1]
		data, err := os.ReadFile(file)
		if err != nil {
			t.Errorf("pip reads %s: %v", file, err)
		}
		call.Files[filepath.Base(file)] = string(data)
		calls = append(calls, call)
		if run != nil {
			stderr, err := run(argv)
			return nil, stderr, err
		}
		return nil, nil, nil
	}
	t.Cleanup(func() { runPrefetchCommand = previous })
	return &calls
}

